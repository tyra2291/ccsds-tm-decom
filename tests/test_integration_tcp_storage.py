_SECURITY_HEADER_BYTES = 14
_CADU_SYNC_LAYER = Layer(name="cadu_sync_marker", header_bytes=4, tail_bytes=0)


async def _fake_cortex_server(reader, writer):
    """Simulates a telemetry front-end: sends two real frames, then closes."""
    writer.write(bytes.fromhex(FRAME_0_HEX))
    writer.write(bytes.fromhex(FRAME_1_HEX))
    await writer.drain()
    writer.close()
    await writer.wait_closed()


def test_tcp_client_stores_decoded_frames_in_database():
    """
    Full chain: a fake CORTEX server sends two real frames over TCP,
    run_tcp_client decodes them, and each result is persisted to an
    ephemeral PostgreSQL container via make_storage_callback. Verifies
    the session and both frames/packets end up correctly stored.
    """
    with PostgresContainer("postgres:16") as postgres:
        dsn = postgres.get_connection_url().replace("postgresql+psycopg2", "postgresql")

        async def run_test():
            pool = await create_pool(dsn)
            try:
                async with pool.acquire() as conn:
                    await conn.execute(_SCHEMA_PATH.read_text())

                session_id = await start_session(
                    pool, name="integration-test", source="tcp:fake-cortex"
                )
                storage_callback = make_storage_callback(pool, session_id)

                server = await asyncio.start_server(_fake_cortex_server, "127.0.0.1", 0)
                port = server.sockets[0].getsockname()[1]

                async with server:
                    client_task = asyncio.create_task(
                        run_tcp_client(
                            host="127.0.0.1",
                            port=port,
                            frame_size=994,
                            layers=[_CADU_SYNC_LAYER],
                            on_frame=storage_callback,
                            security_header_bytes=_SECURITY_HEADER_BYTES,
                        )
                    )
                    await asyncio.wait_for(client_task, timeout=2.0)

                await end_session(pool, session_id)

                async with pool.acquire() as conn:
                    frame_rows = await conn.fetch(
                        "SELECT * FROM frames WHERE session_id = $1 ORDER BY id",
                        session_id,
                    )
                    assert len(frame_rows) == 2
                    assert all(r["spacecraft_id"] == 13 for r in frame_rows)
                    assert all(r["fecf_valid"] for r in frame_rows)

                    packet_rows = await conn.fetch(
                        """
                        SELECT p.* FROM packets p
                        JOIN frames f ON f.id = p.frame_id
                        WHERE f.session_id = $1
                        """,
                        session_id,
                    )
                    assert len(packet_rows) > 0
            finally:
                await pool.close()

        asyncio.run(run_test())